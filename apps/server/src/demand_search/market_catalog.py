def stable_id(value: str) -> str:
    """Stable namespace identities for this version of the simulation."""
    return str(uuid5(_NAMESPACE, f"simulated-market:{SEED_VERSION}:{value}"))


def generate_catalog() -> tuple[list[dict], list[dict]]:
    """Return fresh seed structures without filesystem or network side effects."""
    categories, merchants = [], []
    for category_index, template in enumerate(_TEMPLATES, start=1):
        category_id, label, label_en, aliases, kind, products = template
        categories.append(
            {
                "id": category_id,
                "label": label,
                "label_en": label_en,
                "aliases": list(aliases),
                "merchant_count": 10,
                "offering_count": 30,
            }
        )
        for variant in range(10):
            code = f"SIM-{category_index:02d}-{variant + 1:02d}"
            merchant_id = stable_id(f"merchant:{code}")
            merchant_name = f"模拟商家 {code} · {label}"
            merchant_name_en = f"Fictional merchant {code} · {label_en}"
            region_code = "ABCDEFGHIJ"[(category_index + variant) % 10]
            region = f"虚构区域 {region_code}（非真实地址）"
            region_en = f"Fictional zone {region_code} (not a real address)"
            currency = "USD" if variant == 9 else "CNY"
            offerings = []
            for product_index, product in enumerate(products, start=1):
                (
                    name,
                    name_en,
                    base_price,
                    unit,
                    unit_en,
                    product_aliases,
                    variable_key,
                    variable_base,
                    variable_step,
                    fixed_specs,
                ) = product
                specifications = dict(fixed_specs)
                specifications[variable_key] = round(variable_base + variant * variable_step, 2)
                # Independent synthetic schedules, never an FX conversion.
                multiplier = (1 + variant * 0.07) if currency == "CNY" else 0.19
                amount = round(base_price * multiplier, 2)
                lead_time = 1 + (category_index * 3 + variant * 2 + product_index) % 28
                offerings.append(
                    {
                        "id": stable_id(f"offering:{code}:{product_index}"),
                        "merchant_id": merchant_id,
                        "merchant_name": merchant_name,
                        "merchant_name_en": merchant_name_en,
                        "name": f"{name} · V{variant + 1:02d}",
                        "name_en": f"{name_en} · V{variant + 1:02d}",
                        "category": category_id,
                        "category_label": label,
                        "category_label_en": label_en,
                        "kind": kind,
                        "description": (
                            f"{name}的虚构演示方案；规格、报价与交期均为合成数据。"
                            "无真实库存或销售承诺，未核实资质、认证、配送与适用条件。"
                        ),
                        "description_en": (
                            f"Fictional {name_en.lower()} demonstration. Specifications, prices "
                            "and lead times are synthetic. No real stock or sales commitment. "
                            "Credentials, certification, delivery and suitability are unverified."
                        ),
                        "price": {
                            "amount": amount,
                            "currency": currency,
                            "unit": unit,
                            "unit_en": unit_en,
                            "data_origin": "synthetic",
                        },
                        "specifications": specifications,
                        "lead_time_days": lead_time,
                        "region": region,
                        "region_en": region_en,
                        "data_origin": "synthetic",
                        "aliases": list(dict.fromkeys([name, name_en, *product_aliases])),
                        "created_at": SEED_TIMESTAMP,
                    }
                )
            merchants.append(
                {
                    "id": merchant_id,
                    "name": merchant_name,
                    "name_en": merchant_name_en,
                    "category": category_id,
                    "category_label": label,
                    "category_label_en": label_en,
                    "region": region,
                    "region_en": region_en,
                    "business_type": "模拟商品供应商" if kind == "goods" else "模拟服务提供者",
                    "business_type_en": (
                        "Simulated goods supplier"
                        if kind == "goods"
                        else "Simulated service provider"
                    ),
                    "description": (
                        f"{code} 是固定种子创建的虚构商家资料，不对应任何现实组织。"
                        "全部能力、商品、服务与报价仅供本机协议和搜索演示。"
                    ),
                    "description_en": (
                        f"{code} is a fictional seed profile unrelated to any real organization. "
                        "All capabilities, offerings and prices are local demonstration data."
                    ),
                    "data_origin": "synthetic",
                    "created_at": SEED_TIMESTAMP,
                    "offerings": offerings,
                }
            )
    assert len(categories) == 50 and len(merchants) == 500
    assert sum(len(merchant["offerings"]) for merchant in merchants) == 1500
    return categories, merchants
